/**
 * Convert RGB values to 32-bit RGBA in little-endian format (0xAABBGGRR)
 * This format is compatible with ImageData when using setUint32
 */
function rgbToUint32(r: number, g: number, b: number, a: number = 255): number {
  return (a << 24) | (b << 16) | (g << 8) | r;
}

/**
 * Convert an RGB lookup table to a 32-bit RGBA palette
 */
function rgbTableToPalette(rgbTable: readonly [number, number, number][]): number[] {
  return rgbTable.map(([r, g, b]) => rgbToUint32(r, g, b));
}

